function openRoom(id){
  const r=rooms.find(x=>x.id===id);
  if(!visited.includes(id)){
    visited.push(id);
    localStorage.setItem("mohVisited",JSON.stringify(visited));
    progress();
  }
  
  const contentDiv = document.getElementById("roomContent");
  contentDiv.innerHTML = buildRoomHTML(r);
  
  document.getElementById("roomModal").classList.add("open");
  document.getElementById("roomModal").setAttribute("aria-hidden","false");
  document.body.style.overflow="hidden";
  
  const saved=JSON.parse(localStorage.getItem("mohRoomReflections")||"{}");
  const textarea = document.getElementById("roomReflection");
  if(saved[id] && textarea) textarea.value=saved[id];
  
  // Reset scroll position to top
  document.querySelector(".modal-panel").scrollTop = 0;
}

// Smooth Next Room transition
function nextRoom(id) {
  const contentDiv = document.getElementById("roomContent");
  
  // 1. Start fade out
  contentDiv.classList.add("fade-out");
  
  // 2. Wait for CSS transition to finish (300ms), then load next room
  setTimeout(() => {
    contentDiv.classList.remove("fade-out");
    
    openRoom(id); // Builds HTML and sets scroll to top
    
    // 3. Start fade in
    contentDiv.classList.add("fade-in");
    
    // 4. Clean up fade-in class after it finishes
    setTimeout(() => {
      contentDiv.classList.remove("fade-in");
    }, 400);
  }, 300);
}

function closeRoom(){
  document.getElementById("roomModal").classList.remove("open");
  document.getElementById("roomModal").setAttribute("aria-hidden","true");
  document.body.style.overflow="";
}
function saveRoomReflection(id){
  let s=JSON.parse(localStorage.getItem("mohRoomReflections")||"{}");
  s[id]=document.getElementById("roomReflection").value;
  localStorage.setItem("mohRoomReflections",JSON.stringify(s));
  document.getElementById("roomSaved").textContent="Saved on this device ✓";
}
function playRoomVideo(id, videoIndex=0){
  const r=rooms.find(x=>x.id===id);
  if(r.videoLinks && r.videoLinks[videoIndex]){
    const selectedVideo=r.videoLinks[videoIndex];
    document.getElementById("videoFrame").innerHTML=`<iframe src="https://www.youtube-nocookie.com/embed/${selectedVideo.id}?autoplay=1" title="${selectedVideo.title}" allow="autoplay; encrypted-media; picture-in-picture" allowfullscreen></iframe>`;
    document.getElementById("videoCaption").textContent=selectedVideo.title;
  }else if(r.localVideo){
    document.getElementById("videoFrame").innerHTML=`<video controls autoplay playsinline poster="${r.card}"><source src="${r.localVideo}" type="video/mp4">Your browser cannot play this video. Check that the file exists at ${r.localVideo}.</video>`;
    document.getElementById("videoCaption").textContent=r.videoTitle;
  }else if(r.videoId){
    document.getElementById("videoFrame").innerHTML=`<iframe src="https://www.youtube-nocookie.com/embed/${r.videoId}?autoplay=1" title="${r.videoTitle}" allow="autoplay; encrypted-media; picture-in-picture" allowfullscreen></iframe>`;
    document.getElementById("videoCaption").textContent=r.videoTitle;
  }else{
    alert("No video configured yet. Add a local video path or YouTube ID in js/app.js.");
    return;
  }
  document.getElementById("videoModal").classList.add("open");
}
function closeVideo(){
  document.getElementById("videoModal").classList.remove("open");
  document.getElementById("videoFrame").innerHTML="";
}
